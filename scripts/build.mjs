import { build as viteBuild } from "vite";
import { build as bundle } from "esbuild";
import { mkdir, readdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { resolve, relative, extname } from "node:path";

const root = process.cwd();
await viteBuild();
const documents = ["README.md", "BUILD_NOTES.md", "CONTRACT.md", "VALIDATION.md"];
for (const document of documents) await copyFile(document, resolve("dist/client", document));
await mkdir("dist/client/docs", { recursive: true });
for (const document of documents) await copyFile(document, resolve("dist/client/docs", document));
await mkdir("dist/client/validation", { recursive: true });
for (const file of await readdir("docs/validation")) {
  if (file.endsWith(".json")) await copyFile(resolve("docs/validation", file), resolve("dist/client/validation", file));
}
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".woff2": "font/woff2", ".md": "text/markdown; charset=utf-8", ".json": "application/json; charset=utf-8" };
const assets = {};
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (types[extname(path)]) assets[`/${relative(resolve("dist/client"), path).replaceAll("\\", "/")}`] = { type: types[extname(path)], body: (await readFile(path)).toString("base64") };
  }
}
await collect(resolve("dist/client"));
await writeFile("worker/assets.generated.ts", `// Generated by scripts/build.mjs.\nexport const assets: Record<string, {type: string; body: string}> = ${JSON.stringify(assets)};\n`);
await mkdir("dist/server", { recursive: true });
await bundle({ entryPoints: ["worker/index.ts"], outfile: "dist/server/index.js", bundle: true, format: "esm", platform: "browser", target: "es2022", minify: true, legalComments: "none" });
await mkdir("dist/.openai", { recursive: true });
await copyFile(".openai/hosting.json", "dist/.openai/hosting.json");
console.log(`Built ${Object.keys(assets).length} embedded assets and the D1-backed Worker in ${relative(root, resolve("dist"))}.`);
